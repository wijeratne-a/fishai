def main():
    srcs = sources()
    ids = [r["source_id"] for r in srcs]
    if len(ids) != len(set(ids)):
        dup = sorted({i for i in ids if ids.count(i) > 1})
        raise SystemExit(f"duplicate source_id: {dup}")
    for r in srcs:
        if len(r) != len(COLS):
            raise SystemExit(f"bad width {r['source_id']}")

    out_csv = OUT / "global_data_catalog.csv"
    with out_csv.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=COLS, extrasaction="raise")
        w.writeheader()
        w.writerows(srcs)

    vars_ = variables()
    vnames = [r["variable"] for r in vars_]
    if len(vnames) != len(set(vnames)):
        raise SystemExit("duplicate variable")
    out_v = OUT / "global_ocean_variable_catalog.csv"
    with out_v.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=VCOLS, extrasaction="raise")
        w.writeheader()
        w.writerows(vars_)

    cats = {}
    for r in srcs:
        cats[r["category"]] = cats.get(r["category"], 0) + 1
    print(f"sources={len(srcs)} variables={len(vars_)}")
    for k, n in sorted(cats.items(), key=lambda x: (-x[1], x[0])):
        print(f"  {k}: {n}")


if __name__ == "__main__":
    main()
