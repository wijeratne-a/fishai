def S(**k):
    d = dict(
        attribution_required="YES",
        cost="Free as posted",
        rate_limit="Fair use; identify client; do not parallelize or scrape HTML",
        coordinate_system="WGS84 EPSG:4326",
        taxonomy_standard="none",
        integration_status=NI,
        last_verified_at=VER,
        redistribution_allowed="CONDITIONAL",
        commercial_use_allowed="CONDITIONAL",
        privacy_sensitivity="PUBLIC",
        ecological_sensitivity="low",
        source_reliability="high",
        source_fragility="medium",
        ingestion_priority="P2",
        legal_status="CONDITIONAL_REVIEW_REQUIRED",
        data_format="NetCDF / CSV / API JSON as posted",
        uncertainty="Product-level; retain QC flags; not navigation/harvest-authorization",
        data_quality_controls="Provider QC flags; user must not drop flags",
        fallback_source="",
    )
    tmpl = k.pop("_t", None)
    if tmpl:
        d.update(tmpl)
    d.update(k)
    missing = [c for c in COLS if c not in d]
    if missing:
        raise KeyError(f"{d.get('source_id')}: missing {missing}")
    extra = [c for c in d if c not in COLS]
    if extra:
        raise KeyError(f"{d.get('source_id')}: extra {extra}")
    return d


def V(**k):
    missing = [c for c in VCOLS if c not in k]
    if missing:
        raise KeyError(f"{k.get('variable')}: missing {missing}")
    return k


